#!/usr/bin/env python3
"""Generate includes/abbreviations.md from docs/glossary.md.

Every page gets the file appended (pymdownx.snippets auto_append), so
each abbreviation in the text shows its glossary meaning as a tooltip.
The script takes every glossary row whose term is an abbreviation
(one word with at least two capitals, for example ADL, DvTP, PuB-EAA).

Usage: python3 scripts/gen_abbreviations.py [--check]
  --check  do not write; fail when the file is out of date.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
GLOSSARY = ROOT / "docs" / "glossary.md"
OUT = ROOT / "includes" / "abbreviations.md"
ABBR = re.compile(r"^[A-Z][A-Za-z0-9-]{1,11}$")


def plain(text):
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"[`*]", "", text)
    text = re.sub(r"\s*\([^()]*ADR-\d+[^()]*\)", "", text)
    return " ".join(text.split())


def build():
    rows = []
    for line in GLOSSARY.read_text().splitlines():
        if not line.startswith("|") or set(line) <= set("|-: "):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 2 or cells[0] in ("Term", ""):
            continue
        for term in re.split(r",\s*", cells[0]):
            if ABBR.match(term) and sum(ch.isupper() for ch in term) >= 2:
                # the meaning is the column after "Dutch" when there is one
                meaning = cells[2] if len(cells) >= 4 else cells[1]
                first = plain(meaning).split(". ")[0].rstrip(".")
                rows.append((term, first))
    seen, out = set(), []
    for term, meaning in sorted(rows):
        if term in seen:
            continue
        seen.add(term)
        out.append(f"*[{term}]: {meaning}")
    header = ("<!-- Generated by scripts/gen_abbreviations.py from docs/glossary.md. "
              "Do not edit. -->\n\n")
    return header + "\n".join(out) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("includes/abbreviations.md is out of date; run scripts/gen_abbreviations.py")
            sys.exit(1)
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {text.count('*[')} abbreviations")


if __name__ == "__main__":
    main()
